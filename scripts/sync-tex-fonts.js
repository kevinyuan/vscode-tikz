#!/usr/bin/env node
/**
 * Copies the BaKoMa TeX fonts that node-tikzjax ships into `media/`, so the
 * Markdown preview can load them.
 *
 * Why this is needed: node-tikzjax emits SVG that references TeX fonts by name
 * (`<text font-family="cmmi10">`) with no embedded glyphs. TeX fonts are not
 * Unicode-encoded — a character sits at its position in the font, not at its
 * Unicode codepoint. `\alpha` comes out as U+00AE, `\sum` as U+0050, `\leq` as
 * U+2219. Without the real font loaded the browser substitutes a fallback and
 * renders those literally, as `®`, `P`, `∙` — i.e. mojibake.
 *
 * Run by `npm run compile`. The output is committed so packaging does not depend
 * on node_modules being present or laid out a particular way.
 */

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const srcCssDir = path.join(repoRoot, 'node_modules', 'node-tikzjax', 'css');
const destDir = path.join(repoRoot, 'media', 'tex-fonts');

function main() {
    if (!fs.existsSync(srcCssDir)) {
        console.error(`[sync-tex-fonts] node-tikzjax css directory not found at ${srcCssDir}`);
        console.error('[sync-tex-fonts] Run "npm install" first. Skipping (existing media/tex-fonts is left alone).');
        return;
    }

    const srcTtfDir = path.join(srcCssDir, 'bakoma', 'ttf');
    const destTtfDir = path.join(destDir, 'ttf');
    fs.mkdirSync(destTtfDir, { recursive: true });

    const fonts = fs.readdirSync(srcTtfDir).filter((f) => f.endsWith('.ttf'));
    let copied = 0;
    for (const font of fonts) {
        const from = path.join(srcTtfDir, font);
        const to = path.join(destTtfDir, font);
        // Skip unchanged files so incremental builds stay fast.
        if (fs.existsSync(to) && fs.statSync(to).size === fs.statSync(from).size) { continue; }
        fs.copyFileSync(from, to);
        copied++;
    }

    // Rewrite the stylesheet with paths relative to its new home.
    const upstreamCss = fs.readFileSync(path.join(srcCssDir, 'fonts.css'), 'utf8');
    const css =
        '/* Generated by scripts/sync-tex-fonts.js — do not edit.\n' +
        '   BaKoMa TeX fonts, from node-tikzjax. See ttf/LICENCE. */\n' +
        upstreamCss.replace(/url\('bakoma\/ttf\//g, "url('ttf/");
    fs.writeFileSync(path.join(destDir, 'tex-fonts.css'), css, 'utf8');

    // Carry the font licence along with the fonts.
    const licence = path.join(srcCssDir, 'bakoma', 'LICENCE');
    if (fs.existsSync(licence)) {
        fs.copyFileSync(licence, path.join(destTtfDir, 'LICENCE'));
    }

    console.log(`[sync-tex-fonts] ${fonts.length} fonts available (${copied} copied), stylesheet written`);
}

main();
